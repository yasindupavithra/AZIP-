function slugify(str) {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

const allProducts = [];

for (const group of RAW_CATEGORIES) {
  group.items.forEach((item, idx) => {
    const num = String(idx + 1).padStart(2, '0');
    const id = `${group.prefix}-${num}`;
    const sku = `${group.skuPrefix}-${num}`;
    const slug = `${slugify(item.name)}-${num}`;
    allProducts.push({
      _id: id,
      name: item.name,
      slug,
      description: item.description,
      category: group.category,
      subcategory: item.subcategory,
      price: item.price,
      compareAtPrice: item.compareAtPrice,
      images: [{ url: item.image, alt: item.name }],
      stock: 45 + ((idx * 13) % 110),
      sku,
      tags: item.tags,
      isFeatured: Boolean(item.isFeatured),
      rating: idx % 3 === 0 ? 5.0 : 4.9,
      reviewsCount: 28 + ((idx * 17) % 120),
      badge: item.badge || 'Genuine',
      brand: item.brand,
      grade: item.grade || '',
      language: item.language || '',
      rulingType: item.rulingType || '',
    });
  });
}

